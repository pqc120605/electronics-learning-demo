 await page.getByLabel('Mã nguồn Arduino C++').fill('// in-memory work')
 expect(await page.evaluate(()=>localStorage.getItem('machmo-freestyle-v1'))).toBe(raw)
 await page.getByRole('button',{name:'Bản nháp',exact:true}).click()
 const [download]=await Promise.all([page.waitForEvent('download'),page.getByRole('button',{name:'Tải mạch đang mở',exact:true}).click()])
