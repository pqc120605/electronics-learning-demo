import {expect,test} from '@playwright/test'

for(const width of [375,1440]) {
  test(`sample library runs keypad, environmental inputs and servo at ${width}px`,async({page})=>{
    await page.setViewportSize({width,height:width===375?812:900})
    await page.addInitScript(()=>localStorage.setItem('mm-tour-seen',JSON.stringify({freestyle:1})))
    await page.goto('/app/lab/freestyle?board=esp32-devkit')
    const examples=page.getByRole('combobox',{name:'Mạch mẫu',exact:true})
    const toolbar=page.locator('.freestyle-work-actions')
    await expect(examples.locator('option')).toHaveCount(12)
    await examples.selectOption('keypad-five')
    await page.getByRole('button',{name:'Dựng mạch mẫu',exact:true}).click()
    await toolbar.getByRole('button',{name:'▶ Chạy'}).click()
    await page.getByRole('combobox',{name:/Phím bàn phím 4×4/}).selectOption('5')
    await expect(page.locator('[data-diagram-part="led1"]')).toHaveClass(/is-lit/)
    await page.getByRole('combobox',{name:/Phím bàn phím 4×4/}).selectOption('6')
    await expect(page.locator('[data-diagram-part="led1"]')).not.toHaveClass(/is-lit/)
    await toolbar.getByRole('button',{name:'■ Dừng'}).click()
    await examples.selectOption('ultrasonic')
    await page.getByRole('button',{name:'Dựng mạch mẫu',exact:true}).click()
    await page.getByRole('slider',{name:'Khoảng cách vật cản'}).fill('42')
    await toolbar.getByRole('button',{name:'▶ Chạy'}).click()
    await page.getByRole('tab',{name:/Quan sát/}).click()
    await expect(page.getByLabel('Đầu ra Serial')).toContainText('42.00')
    await toolbar.getByRole('button',{name:'■ Dừng'}).click()
    await page.screenshot({path:`.tmp/l6f-samples-${width}.png`})
    await examples.selectOption('dht-demo')
    await page.getByRole('button',{name:'Dựng mạch mẫu',exact:true}).click()
    await page.getByRole('slider',{name:'Nhiệt độ môi trường'}).fill('31')
    await page.getByRole('slider',{name:'Độ ẩm môi trường'}).fill('64')
    await toolbar.getByRole('button',{name:'▶ Chạy'}).click()
    await page.getByRole('tab',{name:/Quan sát/}).click()
    await expect(page.getByLabel('Đầu ra Serial')).toContainText('31.00 C, 64.00 %RH')
    await toolbar.getByRole('button',{name:'■ Dừng'}).click()
    await examples.selectOption('servo-pulse')
    await page.getByRole('button',{name:'Dựng mạch mẫu',exact:true}).click()
    await toolbar.getByRole('button',{name:'▶ Chạy'}).click()
    await page.getByRole('tab',{name:/Quan sát/}).click()
    await expect(page.locator('.freestyle-outputs')).toContainText('90°')
  })
}
