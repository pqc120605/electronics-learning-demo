const lab = '/learn/digital-lab'

test('learning opens the catalogue and NAND records all four input combinations', async ({ page }) => {
  await page.goto('/topics')
  await page.getByRole('link', { name: 'Mở phòng thực hành IC và giao tiếp số' }).click()
  const nav = page.getByRole('navigation', { name: 'Bài thực hành IC và giao tiếp số' })
  await expect(nav.getByRole('link')).toHaveCount(8)
  await expect(nav.getByRole('link', { name: /Cổng NAND/ })).toHaveAttribute('aria-current', 'page')
  const panel = page.getByRole('region', { name: 'Cổng NAND' })
  for (const [a, b, y] of [[false, false, 1], [false, true, 1], [true, false, 1], [true, true, 0]]) {
    await panel.getByRole('checkbox', { name: /Đầu vào A/ }).setChecked(a)
    await panel.getByRole('checkbox', { name: /Đầu vào B/ }).setChecked(b)
    await panel.getByLabel('Dự đoán Y').selectOption(String(y))
    await panel.getByRole('button', { name: 'Kiểm đầu ra' }).click()
    await expect(panel.getByRole('status')).toHaveText(`Y = ${y} · dự đoán đúng`)
  }
  await expect(panel.getByRole('table').locator('tbody td:last-child')).toHaveText(['1', '1', '1', '0'])
})

