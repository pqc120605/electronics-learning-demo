test('LCD handles scanned addresses, two lines, NACK, power loss and recovery on mobile', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 812 })
  await page.goto('/components?component=lcd1602')
  await page.getByRole('link', { name: 'Gửi chữ tới LCD qua I²C · Thực hành' }).click()
  const panel = page.getByRole('region', { name: 'Gửi chữ tới LCD qua I²C' })
  const scan = panel.getByRole('button', { name: 'Quét bus I²C ảo' })
  const send = panel.getByRole('button', { name: 'Gửi văn bản I²C' })
  const status = panel.getByRole('status')
  const lcd = panel.getByRole('group', { name: 'Hai dòng LCD' })
  await scan.click()
  await expect(status).toContainText('0x27')
  await panel.getByLabel('Nội dung dòng 2').fill('DO XONG')
  await send.click()
  await expect(lcd).toContainText('MACH MO')
  await expect(lcd).toContainText('DO XONG')
  await panel.getByLabel('Địa chỉ gửi').selectOption('63')
  await send.click()
  await expect(status).toContainText('NACK tại 0x3F')
  await expect(lcd).not.toContainText('DO XONG')
  await panel.getByRole('checkbox', { name: 'Cấp nguồn LCD' }).uncheck()
  await scan.click()
  await expect(status).toContainText('không tìm thấy thiết bị')
  await panel.getByRole('checkbox', { name: 'Cấp nguồn LCD' }).check()
  await panel.getByLabel('Địa chỉ của module').selectOption('63')
  await send.click()
  await expect(status).toContainText(/^ACK tại 0x3F/)
  await expect(lcd).toContainText('DO XONG')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(375)
})

test('OLED draws real pixel locations from page writes and rejects wrong address and missing power', async ({ page }) => {
  await page.goto(`${lab}?lab=oled`)
  const panel = page.getByRole('region', { name: 'Ghi điểm ảnh OLED qua I²C' })
  const send = panel.getByRole('button', { name: 'Ghi page OLED' })
  const canvas = panel.getByRole('img', { name: /^OLED/ })
  await send.click()
  await expect(canvas).toHaveAccessibleName(/512 điểm sáng/)
  await panel.getByLabel('Page màn hình').selectOption('7')
  await panel.getByLabel('Byte dữ liệu mỗi cột').selectOption('255')
  await send.click()
  await expect(canvas).toHaveAccessibleName(/1024 điểm sáng/)
  await expect.poll(() => canvas.evaluate(node => {
    const context = node.getContext('2d')
    return [context.getImageData(0, 0, 1, 1).data[1], context.getImageData(0, 63, 1, 1).data[1]]
  })).toEqual([34, 231])
  await panel.getByLabel('Địa chỉ gửi').selectOption('61')
  await send.click()
  await expect(panel.getByRole('status')).toContainText('NACK tại 0x3D')
  await expect(canvas).toHaveAccessibleName(/, 0 điểm sáng/)
  await panel.getByRole('checkbox', { name: 'Cấp nguồn OLED' }).uncheck()
  await panel.getByRole('button', { name: 'Quét bus I²C ảo' }).click()
  await expect(panel.getByRole('status')).toContainText('không tìm thấy thiết bị')
})

