test('the firmware lesson runs compiled Arduino Blink and exports actual AVR8js transitions', async ({ page }) => {
  await page.goto(`/app${lab}?lab=firmware`)
  await page.getByRole('link', { name: 'Mở trình chạy HEX' }).click()
  await expect(page).toHaveURL(/\/app\/tools\/firmware$/)
  await page.getByRole('button', { name: 'Nạp HEX biên dịch từ Arduino IDE' }).click()
  const run = page.getByRole('button', { name: 'Chạy thử', exact: true })
  await expect(run).toBeDisabled()
  await page.getByRole('checkbox', { name: /Tôi xác nhận HEX/ }).check()
  await run.click()
  const exportTrace = page.getByRole('button', { name: 'Tải trace D13 · CSV' })
  await expect(exportTrace).toBeVisible()
  await expect(page.locator('.firmware-avr-frame')).toContainText(/D13: (HIGH|LOW)/)
  const download = page.waitForEvent('download')
  await exportTrace.click()
  const csv = await readFile(await (await download).path(), 'utf8')
  expect(csv).toContain('avr8js,arduino-uno-r3-atmega328p,D13/PB5')
  expect(csv.trim().split('\n').length).toBeGreaterThanOrEqual(3)
})

test('wireless exercise differentiates association, broker and topic failures without network requests', async ({ page }) => {
  await page.goto(`${lab}?lab=wireless`)
  const panel = page.getByRole('region', { name: 'Gửi nhiệt độ qua Wi-Fi và MQTT' })
  await expect(panel).toBeVisible()
  const requests = []
  page.on('request', request => {
    if (['fetch', 'xhr', 'websocket'].includes(request.resourceType())) requests.push(request.url())
  })
  const send = panel.getByRole('button', { name: 'Gửi bản tin QoS 0' })
  const status = panel.getByRole('status')
  await send.click()
  await expect(status).toContainText('{"nhietDo":25}')
  await panel.getByLabel('Topic thuê bao').selectOption('lop/do-am')
  await send.click()
  await expect(status).toContainText('topic khác')
  await expect(status).not.toContainText('nhietDo')
  await panel.getByRole('checkbox', { name: 'Broker đang chạy' }).uncheck()
  await send.click()
  await expect(status).toContainText('broker mô phỏng đang ngoại tuyến', { ignoreCase: true })
  await panel.getByLabel('Điều kiện Wi-Fi').selectOption('wrong-password')
  await send.click()
  await expect(status).toContainText('sai mật khẩu')
  expect(requests).toEqual([])
})
