import { test, expect } from '@playwright/test'

for (const viewport of [{ width: 375, height: 812 }, { width: 1440, height: 900 }]) {
  test(`first experiment, three repairs and project continuation at ${viewport.width}px`, async ({ page }, info) => {
    await page.setViewportSize(viewport)
    await page.goto('/app')
    await page.getByRole('link', { name: 'Thử mạch đầu tiên' }).click()
    const circuit = page.locator('.beginner-circuit')
    await expect(circuit).toBeInViewport()
    await page.screenshot({ path: info.outputPath('first-circuit.png') })
    await page.getByRole('button', { name: 'Bắt đầu thử thách sửa mạch' }).click()
    const check = page.getByRole('button', { name: 'Kiểm tra kết nối' })
    const evidence = page.getByRole('region', { name: 'Bằng chứng sửa mạch' })
    const choose = name => page.getByRole('radio', { name, exact: true }).check()
    const run = async name => {
      await choose(name)
      await check.focus()
      await check.press('Enter')
    }
    await expect(check).toBeDisabled()
    await run('LED sáng')
    await expect(evidence).toContainText('Cần dự đoán đúng và kiểm tra mạch ban đầu')
    await page.getByRole('button', { name: 'Xem gợi ý (0/2)' }).click()
    await expect(page.getByRole('complementary', { name: 'Gợi ý sửa mạch' })).toContainText('cực âm')
    await run('LED tắt')
    await expect(evidence).toContainText('LED tắt')
    await choose('Nối đầu dây về cực âm')
    await page.goto('/app')
    await page.getByRole('link', { name: 'Tiếp tục sửa mạch' }).click()
    await expect(page).toHaveURL(/repair=return-wire$/)
    await expect(page.getByRole('radio', { name: 'Nối đầu dây về cực âm' })).toBeChecked()
    await expect(check).toBeDisabled()
    await run('LED sáng')
    await expect(evidence).toContainText('Đã thực hành: Khôi phục mạch kín')
    await page.getByRole('button', { name: 'Làm tiếp: Tìm lỗ cắm sai dải' }).click()
    await run('Tách rời')
    await choose('Chuyển đầu dây sang 10a')
    await run('Có nối điện')
    await expect(evidence).toContainText('Đã thực hành: Nhận đúng dải nối breadboard')
    await page.getByRole('button', { name: 'Làm tiếp: Sửa LED đặt ngược' }).click()
    await run('LED tắt')
    await choose('Đặt chân A về phía điện trở')
    await run('LED sáng')
    await expect(page.getByText(/3\/3 kỹ năng có bằng chứng trong mô hình/)).toBeVisible()
    await page.screenshot({ path: info.outputPath('three-repairs.png'), fullPage: true })
    await page.getByRole('link', { name: 'Áp dụng vào mini-project' }).click()
    await expect(page.getByRole('link', { name: 'Đèn theo ánh sáng' })).toHaveAttribute('href', '/app/learn/analog-ldr')
    await page.getByLabel('Board của mini-project').selectOption('arduino-uno-r3')
    const prepare = page.getByRole('button', { name: /Chuẩn bị phép thử/ })
    const projectRun = async prediction => {
      await prepare.click()
      await page.getByLabel('Dự đoán LED').selectOption(prediction)
      await page.getByRole('button', { name: 'Chạy và ghi kết quả' }).click()
    }
    for (const prediction of ['off', 'off', 'on', 'off', 'on']) await projectRun(prediction)
    await expect(page.getByText('3/3 kỹ năng có bằng chứng với board và ngưỡng đang chọn.')).toBeVisible()
    await expect(prepare).toHaveCount(0)
    await page.reload()
    await expect(page.getByText('3/3 kỹ năng có bằng chứng với board và ngưỡng đang chọn.')).toBeVisible()
    await page.getByRole('button', { name: 'Đổi ngưỡng sang 70%' }).click()
    await expect(page.getByText('0/3 kỹ năng có bằng chứng với board và ngưỡng đang chọn.')).toBeVisible()
    await expect(page.locator('.capstone-observations > li')).toHaveCount(5)
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(viewport.width)
    await page.screenshot({ path: info.outputPath('project-next-try.png'), fullPage: true })
  })
}

test('mobile title, board search and progressive project list remain accessible', async ({ page }, info) => {
  await page.setViewportSize({ width: 375, height: 812 })
  await page.goto('/app/boards')
  expect(await page.locator('.workspace-current strong').evaluate(title => title.getBoundingClientRect().width)).toBeGreaterThan(95)
  await expect(page.locator('.board-list .board-row')).toHaveCount(8)
  const search = page.getByRole('searchbox', { name: 'Tìm board hoặc vi điều khiển' })
  await search.fill('nucleo')
  await expect(page.locator('.board-list .board-row').getByRole('heading', { name: 'STM32 NUCLEO-F401RE', exact: true })).toBeVisible()
  await expect(page.locator('.board-list .board-row').getByRole('heading', { name: /NUCLEO/i })).toHaveCount(4)
  await search.clear()
  await page.getByRole('button', { name: /Xem thêm \d+ board/ }).click()
  expect(await page.locator('.board-list .board-row').count()).toBeGreaterThan(8)
  await page.goto('/app/projects')
  await expect(page.getByRole('link', { name: 'Mở hoặc tiếp tục mini-project' })).toBeInViewport()
  await expect(page.locator('.project-list > article')).toHaveCount(3)
  await page.getByRole('button', { name: /Xem thêm \d+ bài thực hành/ }).click()
  expect(await page.locator('.project-list > article').count()).toBeGreaterThan(3)
  await page.getByRole('link', { name: 'Mở hoặc tiếp tục mini-project' }).click()
  await expect(page).toHaveURL(/\/app\/learn\/mini-project$/)
  await page.screenshot({ path: info.outputPath('project-entry.png') })
})
