import { test, expect } from '@playwright/test'

async function openSample(page) {
  await page.route('**/api/local-tools/**', route => route.fulfill({ status: 404 }))
  await page.addInitScript(() => localStorage.setItem('mm-tour-seen', '{"freestyle":1}'))
  await page.goto('/build/freestyle')
  await page.getByRole('radio', { name: /Arduino Uno R3/ }).check()
  await page.getByRole('button', { name: 'Dựng mạch mẫu', exact: true }).click()
  await page.getByRole('button', { name: 'Lắp mạch 2D', exact: true }).click()
}

test('wheel zoom and the board pin tooltip work on the same breadboard', async ({ page }) => {
  await openSample(page)
  const frame = page.locator('.breadboard-diagram-scroll')
  const svg = frame.locator('svg')
  const original = await svg.evaluate(element => element.getBoundingClientRect().width)
  await frame.hover()
  await page.mouse.wheel(0, -160)
  await expect.poll(() => svg.evaluate(element => element.getBoundingClientRect().width)).toBeGreaterThan(original)
  const zoomed = await svg.evaluate(element => element.getBoundingClientRect().width)
  await page.mouse.wheel(0, 160)
  await expect.poll(() => svg.evaluate(element => element.getBoundingClientRect().width)).toBeLessThan(zoomed)
  for (let click = 0; click < 3; click++) await page.getByRole('button', { name: 'Thu nhỏ mạch 2D' }).click()
  const reduced = await svg.evaluate(element => element.getBoundingClientRect().width)
  await frame.hover()
  await page.mouse.wheel(0, 160)
  await expect.poll(() => svg.evaluate(element => element.getBoundingClientRect().width)).toBeLessThan(reduced)
  await page.getByRole('button', { name: 'Vừa khung 2D' }).click()
  const pin = frame.getByRole('button', { name: /board:ledOut · D13/ })
  await pin.hover()
  await expect(svg.locator('.diagram-pin-tooltip')).toHaveText('D13')
  expect(await pin.evaluate(element => getComputedStyle(element).cursor)).toBe('pointer')
  await pin.focus()
  await page.getByRole('button', { name: 'Vừa khung 2D' }).hover()
  await expect(svg.locator('.diagram-pin-tooltip')).toHaveText('D13')
  await frame.getByRole('button', { name: 'Thông tin Arduino Uno R3' }).press('Enter')
  const inspector = page.locator('.circuit-part-popup')
  await inspector.getByText('Linh kiện và cổng trên board', { exact: true }).click()
  await expect(inspector.locator('summary').filter({ hasText: /USB/ }).first()).toBeVisible()
  await inspector.getByRole('button', { name: 'Đóng thông tin linh kiện' }).click()
})

test('part values save with units, and moving a wire route leaves endpoints unchanged', async ({ page }) => {
  await openSample(page)
  const stage = page.locator('.freestyle-stage')
  await stage.getByRole('button', { name: /Điện trở.*resistor/ }).first().press('Enter')
  const inspector = stage.locator('.circuit-part-popup')
  await expect(inspector).toBeVisible()
  await inspector.getByLabel('Trị số điện trở', { exact: true }).fill('0')
  await inspector.getByRole('button', { name: 'Áp dụng' }).click()
  await expect(inspector.getByRole('status')).toContainText('lớn hơn 0')
  await inspector.getByLabel('Trị số điện trở', { exact: true }).fill('4,7')
  await inspector.getByLabel('Đơn vị trị số', { exact: true }).selectOption('kΩ')
  await inspector.getByRole('button', { name: 'Áp dụng' }).click()
  await expect(inspector.getByRole('status')).toContainText('4,7 kΩ')
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('machmo-freestyle-v1')).doc.parts.find(part => part.type === 'resistor').value.ohm)).toBe(4700)
  await inspector.getByRole('button', { name: 'Đóng thông tin linh kiện' }).click()

  const wire = stage.locator('[data-diagram-wire]').first()
  await wire.press('Enter')
  const path = wire.locator('.diagram-wire-color')
  const previous = await path.getAttribute('d')
  const raw = await page.evaluate(() => localStorage.getItem('machmo-freestyle-v1'))
  const before = JSON.parse(raw)
  await stage.getByRole('button', { name: /Chỉnh đường đi dây/ }).press('ArrowDown')
  await expect(path).not.toHaveAttribute('d', previous)
  const after = await page.evaluate(() => JSON.parse(localStorage.getItem('machmo-freestyle-v1')))
  expect(after.doc).toEqual(before.doc)
  expect(after.code).toEqual(before.code)
  expect(after.wireLayout?.[await wire.getAttribute('data-diagram-wire')]).toEqual({ x: expect.any(Number), y: expect.any(Number) })
  await stage.getByRole('button', { name: 'Về đường tự động' }).click()
  await expect(path).toHaveAttribute('d', previous)
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('machmo-freestyle-v1')).wireLayout)).toBeUndefined()
})

test('the live waveform opens in the circuit view and can be dismissed', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 812 })
  await openSample(page)
  await page.locator('.freestyle-work-actions').getByRole('button', { name: '▶ Chạy', exact: true }).click()
  const popup = page.getByRole('region', { name: 'Cửa sổ dạng sóng', exact: true })
  await expect(popup.getByRole('heading', { name: 'Dạng sóng logic' })).toBeVisible()
  const graph = popup.locator('.freestyle-wave-channel svg').first()
  await expect(graph).toBeVisible()
  expect(await graph.evaluate(element => {
    const chart = element.getBoundingClientRect()
    const popup = element.closest('.freestyle-wave-popout').getBoundingClientRect()
    return chart.top >= popup.top && chart.bottom <= popup.bottom
  })).toBe(true)
  await expect(page.getByRole('button', { name: 'Lắp mạch 2D', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await popup.getByRole('button', { name: 'Đóng dạng sóng' }).click()
  await expect(popup).toHaveCount(0)
  await expect(page.locator('.freestyle-trace-dock summary')).toBeVisible()
})
