import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'

const store = 'machmo-freestyle-v1'

test('wire bends survive view switches, reload and draft export/import with bounded undo', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('mm-tour-seen', JSON.stringify({ freestyle: 1 })))
  await page.goto('/build/freestyle')
  await page.getByRole('radio', { name: /Arduino Uno R3/ }).check()
  await page.getByRole('button', { name: 'Dựng mạch mẫu' }).click()
  await page.getByRole('button', { name: 'Lắp mạch 2D', exact: true }).click()
  const first = page.locator('[data-diagram-wire="w1"]')
  const wire = first.locator('path').last()
  const select = () => first.press('Enter')
  const bend = page.getByRole('button', { name: /Chỉnh đường đi dây w1/ })
  const undo = page.getByRole('button', { name: 'Hoàn tác dây' })
  await select()
  const original = await wire.getAttribute('d')
  const snapshot = () => page.evaluate(key => JSON.parse(localStorage.getItem(key)), store)
  const before = await snapshot()
  await bend.press('ArrowDown')
  await expect(wire).not.toHaveAttribute('d', original)
  const moved = await wire.getAttribute('d')
  expect((await snapshot()).doc).toEqual(before.doc)
  expect((await snapshot()).wireLayout.w1).toBeTruthy()
  await undo.click()
  await expect(wire).toHaveAttribute('d', original)
  expect((await snapshot()).wireLayout).toBeUndefined()
  await select()
  await bend.press('ArrowDown')
  await page.getByRole('button', { name: 'Schematic', exact: true }).click()
  await page.getByRole('button', { name: 'Lắp mạch 2D', exact: true }).click()
  await expect(wire).toHaveAttribute('d', moved)
  await page.goto('/build/freestyle?resume=1')
  await expect(wire).toHaveAttribute('d', moved)
  await expect(undo).toBeDisabled()

  await page.getByRole('button', { name: 'Bản nháp', exact: true }).click()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Tải mạch đang mở' }).click()
  const raw = await readFile(await (await download).path())
  await page.getByRole('button', { name: 'Đóng bản nháp' }).click()
  await page.getByRole('button', { name: 'Bàn trống', exact: true }).click()
  await page.getByLabel('Nhập bản nháp từ file').setInputFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from('{') })
  await expect(page.getByText('Không đọc được file nháp. Mạch hiện tại được giữ.')).toBeVisible()
  await page.getByLabel('Nhập bản nháp từ file').setInputFiles({ name: 'wire-bent.json', mimeType: 'application/json', buffer: raw })
  await expect(wire).toHaveAttribute('d', moved)
  expect((await snapshot()).doc).toEqual(before.doc)
  expect((await snapshot()).code).toEqual(before.code)
})

test('mobile resume exposes the saved circuit immediately and stale wire edits stay in the tab', async ({ page, context }) => {
  await page.setViewportSize({ width: 375, height: 812 })
  await context.addInitScript(() => localStorage.setItem('mm-tour-seen', JSON.stringify({ freestyle: 1 })))
  await page.goto('/build/freestyle')
  await page.getByRole('radio', { name: /Arduino Uno R3/ }).check()
  await page.getByRole('button', { name: 'Dựng mạch mẫu' }).click()
  const newer = await context.newPage()
  await newer.setViewportSize({ width: 375, height: 812 })
  await newer.goto('/build/freestyle?resume=1')
  const firstNew = newer.locator('[data-diagram-wire="w1"]')
  await expect(firstNew).toBeVisible()
  const original = await newer.evaluate(key => localStorage.getItem(key), store)

  await newer.getByRole('group', { name: 'Bản nháp và thao tác dây' }).scrollIntoViewIfNeeded()
  const actions = await newer.getByRole('group', { name: 'Bản nháp và thao tác dây' }).boundingBox()
  expect(actions.x + actions.width).toBeLessThanOrEqual(375)
  await firstNew.press('Enter')
  await newer.getByRole('button', { name: /Chỉnh đường đi dây w1/ }).press('ArrowRight')
  const saved = await newer.evaluate(key => localStorage.getItem(key), store)
  expect(saved).not.toBe(original)
  await page.getByRole('button', { name: 'Lắp mạch 2D', exact: true }).click()
  await page.locator('[data-diagram-wire="w1"]').press('Enter')
  await page.getByRole('button', { name: /Chỉnh đường đi dây w1/ }).press('ArrowDown')
  await expect(page.getByText('Chưa lưu vào trình duyệt', { exact: false }).first()).toBeVisible()
  expect(await page.evaluate(key => localStorage.getItem(key), store)).toBe(saved)
})
