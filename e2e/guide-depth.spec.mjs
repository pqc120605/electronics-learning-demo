import { test, expect } from '@playwright/test'
const seed = async page => page.addInitScript(() => localStorage.setItem('mm-tour-seen',JSON.stringify(Object.fromEntries(['home','app-home','library','tools','lesson','lab','freestyle'].map(id=>[id,1])))))
async function openGuide(page) {
  await page.getByRole('button',{name:'Trợ giúp',exact:true}).click()
  await page.locator('.help-menu-panel').getByRole('button',{name:/Hỏi Mở/}).click()
  const panel=page.getByRole('dialog',{name:'Mở — bạn đồng hành học điện tử'})
  await expect(panel).toBeVisible()
  await panel.getByRole('button',{name:'Hỏi đáp',exact:true}).click()
  return panel
}
async function ask(panel,q){await panel.getByRole('textbox',{name:'Câu hỏi của bạn'}).fill(q);await panel.getByRole('button',{name:'Tìm câu trả lời',exact:true}).click()}
for(const width of [375,1440]) test(`professional catalog answer keeps official source and local context ${width}px`,async({page})=>{
  await seed(page)
  await page.setViewportSize({width,height:900})
  await page.goto('/app/boards?board=arduino-uno-r3')
  const panel=await openGuide(page)
  await expect(panel.locator('canvas')).toHaveAttribute('data-status','ready')
  const external=[]
  page.on('request',request=>{if(new URL(request.url()).origin!==new URL(page.url()).origin)external.push(request.url())})
  await ask(panel,'Arduino Uno R3 ADC và mức logic có giới hạn gì?')
  await expect(panel.locator('.guide-results')).toContainText('1023')
  const official=panel.locator('.guide-sources a[href*="docs.arduino.cc/"]').first()
  await expect(official).toHaveAttribute('target','_blank')
  await expect(official).toHaveAttribute('rel',/noopener/)
  await expect(panel.getByRole('link',{name:'Mở hồ sơ board'})).toHaveAttribute('href','/app/boards?board=arduino-uno-r3')
  await ask(panel,'board đang chọn có ADC thế nào')
  await expect(panel.locator('.guide-results h3').first()).toHaveText('Arduino Uno R3')
  await ask(panel,'Toshiba TB6612FNG dùng như thế nào')
  await expect(panel.locator('.guide-results')).toContainText('VM')
  await expect(panel.locator('.guide-results')).toContainText('STBY')
  await expect(panel.locator('.guide-sources a[href*="toshiba.semicon-storage.com/"]')).toHaveCount(1)
  await expect(panel.locator('.guide-results')).toContainText(/không đại diện mọi board TB6612/i)
  await ask(panel,'Thông số board clone XZQ-987 GPIO 999')
  await expect(panel.locator('.guide-unknown')).toBeVisible()
  await expect(panel.locator('.guide-results article')).toHaveCount(0)
  expect(external).toEqual([])
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
})
