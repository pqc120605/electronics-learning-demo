import { expect, test } from '@playwright/test'

for (const width of [375, 1440]) {
  test(`calculates and applies the E24 resistor from the LED inspector at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: width === 375 ? 812 : 900 })
    await page.addInitScript(() => localStorage.setItem('mm-tour-seen', JSON.stringify({ freestyle: 1 })))
    await page.goto('/app/lab/freestyle?board=arduino-uno-r3')
    await page.getByRole('button', { name: 'Dựng mạch mẫu', exact: true }).click()
    const resistor = page.locator('[data-diagram-part="resistor1"] .diagram-part-body-control')
    await resistor.press('Enter')
    await page.getByLabel('Trị số điện trở', { exact: true }).fill('330')
    await page.getByRole('button', { name: 'Áp dụng', exact: true }).click()
    await page.getByRole('button', { name: 'Đóng thông tin linh kiện' }).click()
    const led = page.locator('[data-diagram-part="led1"] .diagram-part-body-control')
    await led.press('Enter')
    const inspector = page.getByRole('complementary', { name: /LED led1/ })
    await inspector.getByText('Tính điện trở LED', { exact: true }).click()
    await expect(inspector).toContainText('board là 5 V')
    await inspector.getByLabel('Vf LED (V)').fill('5')
    await inspector.getByRole('button', { name: 'Tính và áp dụng giá trị E24' }).click()
    await expect(inspector.getByRole('status')).toContainText('lớn hơn Vf')
    await inspector.getByLabel('Vf LED (V)').fill('2')
    await inspector.getByRole('button', { name: 'Tính và áp dụng giá trị E24' }).click()
    await expect(inspector.getByRole('status')).toContainText('620 Ω')
    await page.screenshot({ path: `.tmp/l3-led-calculator-${width}.png` })
    await inspector.getByRole('button', { name: 'Đóng thông tin linh kiện' }).click()
    await resistor.press('Enter')
    await expect(page.getByLabel('Trị số điện trở', { exact: true })).toHaveValue('620')
    await page.getByRole('button', { name: 'Đóng thông tin linh kiện' }).click()
    await page.getByRole('button', { name: 'Hoàn tác mạch', exact: true }).click()
    await resistor.press('Enter')
    await expect(page.getByLabel('Trị số điện trở', { exact: true })).toHaveValue('330')
  })
}
