import { test, expect } from '@playwright/test'

const activeKey = 'machmo-local-capstone-v1'
const libraryKey = 'machmo-local-capstone-library-v1'
const active = page => page.evaluate(key => JSON.parse(localStorage.getItem(key)).report, activeKey)
const entries = page => page.evaluate(key => JSON.parse(localStorage.getItem(key)).entries, libraryKey)

for (const width of [375, 1440]) {
  test(`named mini-project snapshots open and copy safely from Projects at ${width}px`, async ({ page }, testInfo) => {
    await page.setViewportSize({ width, height: 900 })
    await page.goto('/app/learn/mini-project')
    await page.getByLabel('Board của mini-project').selectOption('arduino-uno-r3')
    await page.getByLabel('Ghi lại lỗi đã thấy và cách bạn sửa').fill('Bản ngưỡng ban đầu')
    const original = await active(page)
    await page.getByLabel('Tên bản lưu').fill('Ngưỡng 50')
    await page.getByRole('button', { name: 'Lưu bản vào thư viện' }).click()
    await page.getByLabel('Ghi lại lỗi đã thấy và cách bạn sửa').fill('Đang sửa riêng')
    await page.goto('/app/projects')
    const library = page.getByRole('region', { name: 'Thư viện mini-project' })
    await expect(library.getByRole('heading', { name: 'Ngưỡng 50', exact: true })).toBeVisible()
    await library.getByRole('button', { name: 'Tạo bản sao độc lập Ngưỡng 50', exact: true }).click()
    const saved = await entries(page)
    expect(JSON.parse(saved[1].report).report).toEqual(original)
    expect(JSON.parse(saved[0].report).report.projectId).not.toBe(original.projectId)
    expect((await active(page)).notes).toBe('Đang sửa riêng')
    await library.getByRole('button', { name: 'Mở Ngưỡng 50', exact: true }).click()
    await library.getByRole('button', { name: 'Hủy thao tác thư viện' }).click()
    expect((await active(page)).notes).toBe('Đang sửa riêng')
    await library.getByRole('button', { name: 'Mở Ngưỡng 50', exact: true }).click()
    await library.getByRole('button', { name: 'Xác nhận mở và thay hồ sơ đang làm' }).click()
    await expect(page).toHaveURL(/\/app\/learn\/mini-project$/)
    await expect(page.getByLabel('Ghi lại lỗi đã thấy và cách bạn sửa')).toHaveValue('Bản ngưỡng ban đầu')
    expect((await active(page)).projectId).toBe(original.projectId)
    await page.reload()
    await expect(page.getByLabel('Board của mini-project')).toHaveValue('arduino-uno-r3')
    await page.getByRole('button', { name: 'Mở Ngưỡng 50 · bản sao', exact: true }).click()
    await page.getByRole('button', { name: 'Xác nhận mở và thay hồ sơ đang làm' }).click()
    expect((await active(page)).projectId).not.toBe(original.projectId)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: testInfo.outputPath(`portfolio-${width}.png`), fullPage: true })
  })
}

test('stale tabs cannot overwrite active report or the library', async ({ page, context }) => {
  await page.goto('/learn/mini-project')
  await page.getByLabel('Board của mini-project').selectOption('arduino-nano')
  const other = await context.newPage()
  await other.goto('/learn/mini-project')
  await other.getByLabel('Tên bản lưu').fill('Đang soạn ở tab hai')
  await expect(other.getByRole('button', { name: 'Lưu bản vào thư viện' })).toBeEnabled()
  await page.getByLabel('Tên bản lưu').fill('Tab một')
  await page.getByRole('button', { name: 'Lưu bản vào thư viện' }).click()
  await expect(other.getByRole('button', { name: 'Lưu bản vào thư viện' })).toBeDisabled()
  await other.getByRole('button', { name: 'Làm mới thư viện' }).click()
  await expect(other.getByRole('heading', { name: 'Tab một', exact: true })).toBeVisible()
  await page.getByLabel('Ghi lại lỗi đã thấy và cách bạn sửa').fill('Thay đổi ở tab một')
  await expect(other.getByText('Tab này đã khóa ghi', { exact: false })).toBeVisible()
  await other.getByLabel('Ghi lại lỗi đã thấy và cách bạn sửa').fill('Bản trong bộ nhớ tab hai')
  expect((await active(other)).notes).toBe('Thay đổi ở tab một')
  await other.getByRole('button', { name: 'Mở Tab một', exact: true }).click()
  await other.getByRole('button', { name: 'Xác nhận mở và thay hồ sơ đang làm' }).click()
  expect((await active(other)).notes).toBe('Thay đổi ở tab một')
})

test('damaged library is downloadable and never replaced; quota retains draft', async ({ page }) => {
  await page.goto('/learn/mini-project')
  await page.evaluate(key => localStorage.setItem(key, '{damaged-original'), libraryKey)
  await page.reload()
  await expect(page.getByRole('button', { name: 'Lưu bản vào thư viện' })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Tải thư viện gốc' })).toBeVisible()
  expect(await page.evaluate(key => localStorage.getItem(key), libraryKey)).toBe('{damaged-original')
  await page.getByRole('button', { name: 'Bắt đầu thư viện mới' }).click()
  await page.getByRole('button', { name: 'Sao lưu và mở thư viện trống' }).click()
  await expect(page.getByRole('button', { name: 'Tải thư viện đã sao lưu' })).toBeVisible()
  expect(await page.evaluate(key => localStorage.getItem(`${key}:recovery`), libraryKey)).toBe('{damaged-original')
  await page.getByLabel('Ghi lại lỗi đã thấy và cách bạn sửa').fill('Giữ bản khi đầy')
  await page.evaluate(() => { Storage.prototype.setItem = () => { throw new DOMException('quota', 'QuotaExceededError') } })
  await page.getByLabel('Tên bản lưu').fill('Không ghi được')
  await page.getByRole('button', { name: 'Lưu bản vào thư viện' }).click()
  await expect(page.getByText('Không ghi được thư viện:', { exact: false })).toBeVisible()
  await expect(page.getByLabel('Ghi lại lỗi đã thấy và cách bạn sửa')).toHaveValue('Giữ bản khi đầy')
  expect(JSON.parse(await page.evaluate(key => localStorage.getItem(key), libraryKey)).entries).toEqual([])
})
