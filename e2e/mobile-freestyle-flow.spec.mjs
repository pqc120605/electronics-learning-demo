import { test, expect } from '@playwright/test'

test('mobile pointer reveals each chosen board and added part while keyboard browsing stays in the picker', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 812 })
  await page.addInitScript(() => localStorage.setItem('mm-tour-seen', JSON.stringify({ freestyle: 1 })))
  await page.goto('/build/freestyle')
  const stage = page.locator('.freestyle-stage')
  const boardStep = page.getByRole('tab', { name: /Chọn board/ })
  const first = page.getByRole('radio', { name: /Arduino Nano classic/ })
  await first.check()
  await expect(stage).toBeFocused()
  await expect(stage.locator('[data-board-art="arduino-nano"]')).toBeVisible()
  await boardStep.click()
  await first.focus()
  await page.keyboard.press('ArrowLeft')
  const uno = page.getByRole('radio', { name: /Arduino Uno R3/ })
  await expect(uno).toBeChecked()
  await expect(uno).toBeFocused()
  await expect(stage).toBeHidden()
  await first.check()
  await expect(stage.locator('[data-board-art="arduino-nano"]')).toBeVisible()
  await boardStep.click()
  await uno.check()
  await expect(stage.locator('[data-board-art="arduino-uno-r3"]')).toBeVisible()
  const partsStep = page.getByRole('tab', { name: /Thêm linh kiện/ })
  await partsStep.click()
  await page.getByRole('button', { name: 'Thêm LED', exact: true }).click()
  await expect(stage).toBeFocused()
  await expect(stage.locator('[data-diagram-part="led1"]')).toBeVisible()
  await expect(page.getByRole('button', { name: '▶ Chạy', exact: true })).toBeInViewport()
  await stage.getByRole('button', { name: /Xem linh kiện LED/ }).click()
  await expect(page.locator('.freestyle-selected')).toBeFocused()
  await expect(page.locator('.freestyle-selected')).toContainText('led1')
})

test('desktop can compare boards with the controls and circuit visible together', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/build/freestyle')
  const uno = page.getByRole('radio', { name: /Arduino Uno R3/ })
  await uno.check()
  await expect(uno).toBeVisible()
  await expect(page.locator('.freestyle-stage [data-board-art="arduino-uno-r3"]')).toBeVisible()
})
