import {expect,test} from '@playwright/test'

for(const width of [375,1440]) {
  test(`group editor duplicates and recovers circuit edits at ${width}px`,async({page})=>{
    await page.setViewportSize({width,height:width===375?812:900})
    await page.addInitScript(()=>localStorage.setItem('mm-tour-seen',JSON.stringify({freestyle:1})))
    await page.goto('/app/lab/freestyle?board=arduino-uno-r3')
    await page.getByRole('button',{name:'Dựng mạch mẫu',exact:true}).click()
    const part=id=>page.locator(`[data-diagram-part="${id}"] .diagram-part-body-control`)
    await part('led1').press('Shift+Enter')
    await part('resistor1').press('Shift+Enter')
    await expect(part('led1')).toHaveAttribute('aria-pressed','true')
    await expect(part('resistor1')).toHaveAttribute('aria-pressed','true')
    await part('resistor1').press('Control+d')
    await expect(part('led2')).toHaveCount(1)
    await expect(part('resistor2')).toHaveCount(1)
    await part('resistor2').press('Control+z')
    await expect(part('led2')).toHaveCount(0)
    await page.getByRole('button',{name:'Làm lại mạch',exact:true}).click()
    await expect(part('led2')).toHaveCount(1)
    await part('led2').press('Shift+Enter')
    await part('led2').press('Delete')
    await expect(part('led2')).toHaveCount(0)
    await page.getByRole('button',{name:'Hoàn tác mạch',exact:true}).click()
    await expect(part('led2')).toHaveCount(1)
    const ledX=await part('led1').getAttribute('transform')
    await part('led1').press('Shift+Enter')
    await part('led1').press('ArrowUp')
    await expect(part('led1')).not.toHaveAttribute('transform',ledX)
    await part('led1').press('r')
    await expect(part('led1')).toHaveAttribute('transform',/rotate\(-?180\)/)
    await part('led2').press('Shift+?')
    await expect(page.getByRole('button',{name:'Phím tắt'})).toHaveAttribute('aria-expanded','true')
    await page.screenshot({path:`.tmp/l6g-editor-${width}.png`})
  })
}

test('desktop drag selects the component centers without starting a wire', async ({page})=>{
  await page.setViewportSize({width:1440,height:900})
  await page.addInitScript(()=>localStorage.setItem('mm-tour-seen',JSON.stringify({freestyle:1})))
  await page.goto('/app/lab/freestyle?board=arduino-uno-r3')
  await page.getByRole('button',{name:'Dựng mạch mẫu',exact:true}).click()
  await page.getByRole('button',{name:'Vừa khung 2D',exact:true}).click()
  const svg=page.locator('.breadboard-diagram-svg')
  await svg.scrollIntoViewIfNeeded()
  const points=await svg.evaluate(element=>{
    const control=element.querySelector('[data-diagram-part="led1"] .diagram-part-body-control')
    const center=new DOMPoint(0,0).matrixTransform(control.getScreenCTM())
    const bounds=element.getBoundingClientRect()
    return {from:[bounds.left+5,Math.max(60,bounds.top+5)],to:[center.x+10,center.y+18]}
  })
  await page.keyboard.down('Shift')
  await page.mouse.move(...points.from)
  await page.mouse.down()
  await page.mouse.move(...points.to,{steps:10})
  await page.mouse.up()
  await page.keyboard.up('Shift')
  await expect(page.locator('[data-diagram-part="led1"] .diagram-part-body-control')).toHaveAttribute('aria-pressed','true')
  await expect(page.locator('[data-diagram-part="resistor1"] .diagram-part-body-control')).toHaveAttribute('aria-pressed','true')
  await expect(page.locator('[data-diagram-wire]')).toHaveCount(4)
})
