test('Back and Forward restore each board code draft', async ({ page }) => {
  await quiet(page)
  await page.goto('/app/learn/button-led?board=arduino-uno-r3')
  const inspector = page.getByRole('complementary', { name: 'Chi tiết bài và mạch' })
  const board = inspector.getByLabel('Board của bạn')
  const code = inspector.getByLabel('Code bài nút nhấn')
  const showCode = () => inspector.getByRole('button', { name: 'Code', exact: true }).click()
  const showBoard = () => inspector.getByRole('button', { name: 'Bài học', exact: true }).click()
  await showCode()
  await code.fill('// nháp Uno')
  await showBoard()
  await board.selectOption('arduino-nano-classic')
  await expect(page).toHaveURL(/board=arduino-nano-classic/)
  await showCode()
  await expect(code).not.toHaveValue('// nháp Uno')
  await code.fill('// nháp Nano')
  await page.goBack()
  await expect(page).toHaveURL(/board=arduino-uno-r3/)
  await expect(code).toHaveValue('// nháp Uno')
  await page.goForward()
  await expect(page).toHaveURL(/board=arduino-nano-classic/)
  await expect(code).toHaveValue('// nháp Nano')
})
